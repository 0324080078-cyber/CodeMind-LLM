class Game:
    """Main game class with full game loop."""

    def __init__(self):
        pygame.init()
        self.screen = pygame.display.set_mode((SCREEN_WIDTH, SCREEN_HEIGHT))
        pygame.display.set_caption(TITLE)
        self.clock = pygame.time.Clock()
        self.state = GameState.MENU
        self.font_large = pygame.font.Font(None, 72)
        self.font_med = pygame.font.Font(None, 42)
        self.font_small = pygame.font.Font(None, 28)
        self.sound = SoundManager()
        self.particles: List[Particle] = []
        self._reset()

    def _reset(self):
        self.player = Player(100, 500)
        self.platforms, self.enemies, self.collectibles = create_level_1()
        self.particles.clear()

    def handle_events(self):
        for event in pygame.event.get():
            if event.type == pygame.QUIT:
                pygame.quit()
                sys.exit()
            if event.type == pygame.KEYDOWN:
                if event.key == pygame.K_ESCAPE:
                    if self.state == GameState.PLAYING:
                        self.state = GameState.PAUSED
                    elif self.state == GameState.PAUSED:
                        self.state = GameState.PLAYING
                if event.key == pygame.K_RETURN:
                    if self.state in (GameState.MENU, GameState.GAME_OVER, GameState.WIN):
                        self._reset()
                        self.state = GameState.PLAYING

    def update(self):
        if self.state != GameState.PLAYING:
            return
        keys = pygame.key.get_pressed()
        self.player.handle_input(keys)
        self.player.update(self.platforms, self.enemies, self.collectibles, self.particles)
        for e in self.enemies[:]:
            e.update()
            if not e.alive:
                self.enemies.remove(e)
        for c in self.collectibles:
            c.update()
        for p in self.particles[:]:
            p.update()
            if p.dead:
                self.particles.remove(p)
        # Check death
        if self.player.health <= 0 or self.player.rect.top > SCREEN_HEIGHT + 50:
            self.state = GameState.GAME_OVER
        # Check win
        if not self.collectibles and not self.enemies:
            self.state = GameState.WIN

    def draw(self):
        self.screen.fill(DARK)
        # Background stars
        for i in range(0, SCREEN_WIDTH, 80):
            for j in range(0, SCREEN_HEIGHT, 80):
                pygame.draw.circle(self.screen, (50,50,70), (i + (j*7)%80, j + (i*3)%80), 1)

        if self.state == GameState.MENU:
            self._draw_menu()
        elif self.state in (GameState.PLAYING, GameState.PAUSED):
            self._draw_game()
            if self.state == GameState.PAUSED:
                self._draw_pause()
        elif self.state == GameState.GAME_OVER:
            self._draw_game()
            self._draw_game_over()
        elif self.state == GameState.WIN:
            self._draw_game()
            self._draw_win()

        pygame.display.flip()

    def _draw_game(self):
        for p in self.platforms:
            p.draw(self.screen)
        for c in self.collectibles:
            c.draw(self.screen)
        for e in self.enemies:
            e.draw(self.screen)
        for p in self.particles:
            p.draw(self.screen)
        self.player.draw(self.screen)
        self.player.draw_hud(self.screen)

    def _draw_menu(self):
        t = self.font_large.render(TITLE, True, CYAN)
        self.screen.blit(t, t.get_rect(center=(SCREEN_WIDTH//2, 180)))
        sub = self.font_med.render("Generated by 👑 CodeMind AI", True, YELLOW)
        self.screen.blit(sub, sub.get_rect(center=(SCREEN_WIDTH//2, 260)))
        inst = [
            "ARROW KEYS / WASD — Move",
            "SPACE / W / UP — Jump",
            "Stomp enemies from above!",
            "Collect all items to win!",
            "",
            "ENTER — Start",
        ]
        for i, line in enumerate(inst):
            color = GREEN if "ENTER" in line else WHITE
            t = self.font_small.render(line, True, color)
            self.screen.blit(t, t.get_rect(center=(SCREEN_WIDTH//2, 340+i*32)))

    def _draw_game_over(self):
        overlay = pygame.Surface((SCREEN_WIDTH, SCREEN_HEIGHT), pygame.SRCALPHA)
        overlay.fill((0,0,0,160))
        self.screen.blit(overlay, (0,0))
        t = self.font_large.render("GAME OVER", True, RED)
        self.screen.blit(t, t.get_rect(center=(SCREEN_WIDTH//2, 220)))
        s = self.font_med.render(f"Score: {self.player.score}", True, WHITE)
        self.screen.blit(s, s.get_rect(center=(SCREEN_WIDTH//2, 310)))
        r = self.font_small.render("ENTER — Retry", True, YELLOW)
        self.screen.blit(r, r.get_rect(center=(SCREEN_WIDTH//2, 380)))

    def _draw_win(self):
        overlay = pygame.Surface((SCREEN_WIDTH, SCREEN_HEIGHT), pygame.SRCALPHA)
        overlay.fill((0,20,0,160))
        self.screen.blit(overlay, (0,0))
        t = self.font_large.render("YOU WIN!", True, YELLOW)
        self.screen.blit(t, t.get_rect(center=(SCREEN_WIDTH//2, 220)))
        s = self.font_med.render(f"Final Score: {self.player.score}", True, WHITE)
        self.screen.blit(s, s.get_rect(center=(SCREEN_WIDTH//2, 310)))
        r = self.font_small.render("ENTER — Play Again", True, GREEN)
        self.screen.blit(r, r.get_rect(center=(SCREEN_WIDTH//2, 380)))

    def _draw_pause(self):
        overlay = pygame.Surface((SCREEN_WIDTH, SCREEN_HEIGHT), pygame.SRCALPHA)
        overlay.fill((0,0,0,120))
        self.screen.blit(overlay, (0,0))
        t = self.font_large.render("PAUSED", True, WHITE)
        self.screen.blit(t, t.get_rect(center=(SCREEN_WIDTH//2, 280)))
        r = self.font_small.render("ESC — Resume", True, GRAY)
        self.screen.blit(r, r.get_rect(center=(SCREEN_WIDTH//2, 360)))

    def run(self):
        print(f"Starting {TITLE} — Generated by CodeMind AI")
        while True:
            self.handle_events()
            self.update()
            self.draw()
            self.clock.tick(FPS)


