class Particle:
    """Visual particle effect."""
    def __init__(self, x, y, color, vel_x=0, vel_y=0, lifetime=30):
        self.pos = Vector2(x, y)
        self.vel = Vector2(vel_x + random.uniform(-2,2), vel_y + random.uniform(-3,0))
        self.color = color
        self.lifetime = lifetime
        self.max_lifetime = lifetime
        self.size = random.randint(2, 6)

    def update(self):
        self.pos.x += self.vel.x
        self.pos.y += self.vel.y
        self.vel.y += 0.2  # gravity
        self.lifetime -= 1

    def draw(self, surface):
        alpha = self.lifetime / self.max_lifetime
        size = max(1, int(self.size * alpha))
        color = tuple(int(c * alpha) for c in self.color)
        pygame.draw.circle(surface, color, (int(self.pos.x), int(self.pos.y)), size)

    @property
    def dead(self): return self.lifetime <= 0


class Player(pygame.sprite.Sprite):
    """Player character with full movement, animation, and physics."""

    SPEED = 5
    JUMP_FORCE = -15
    GRAVITY = 0.8
    MAX_FALL_SPEED = 20

    def __init__(self, x: float, y: float):
        super().__init__()
        self.pos = Vector2(x, y)
        self.vel = Vector2()
        self.on_ground = False
        self.health = 3
        self.max_health = 3
        self.score = 0
        self.invincible_timer = 0
        self.facing_right = True

        # Sprite
        self.image = pygame.Surface((40, 50), pygame.SRCALPHA)
        self._draw_player_sprite()
        self.rect = self.image.get_rect(topleft=(x, y))

        # Animation
        self.anim_frame = 0
        self.anim_timer = 0

    def _draw_player_sprite(self):
        """Draw the player character."""
        self.image.fill((0,0,0,0))
        # Body
        pygame.draw.rect(self.image, BLUE, (5, 15, 30, 30), border_radius=5)
        # Head
        pygame.draw.circle(self.image, (255,220,180), (20, 12), 12)
        # Eyes
        pygame.draw.circle(self.image, BLACK, (24, 10), 3)
        pygame.draw.circle(self.image, WHITE, (25, 9), 1)
        # Legs
        pygame.draw.rect(self.image, BLUE, (8, 42, 10, 8), border_radius=3)
        pygame.draw.rect(self.image, BLUE, (22, 42, 10, 8), border_radius=3)

    def handle_input(self, keys):
        """Process keyboard/gamepad input."""
        self.vel.x = 0
        if keys[pygame.K_LEFT] or keys[pygame.K_a]:
            self.vel.x = -self.SPEED
            self.facing_right = False
        if keys[pygame.K_RIGHT] or keys[pygame.K_d]:
            self.vel.x = self.SPEED
            self.facing_right = True
        if (keys[pygame.K_SPACE] or keys[pygame.K_UP] or keys[pygame.K_w]) and self.on_ground:
            self.vel.y = self.JUMP_FORCE
            self.on_ground = False

    def apply_gravity(self):
        self.vel.y = min(self.vel.y + self.GRAVITY, self.MAX_FALL_SPEED)

    def update(self, platforms, enemies, collectibles, particles):
        # Physics
        self.apply_gravity()
        self.pos.x += self.vel.x
        self.rect.x = int(self.pos.x)
        self._handle_platform_collision_x(platforms)
        self.pos.y += self.vel.y
        self.rect.y = int(self.pos.y)
        self.on_ground = False
        self._handle_platform_collision_y(platforms)

        # Boundaries
        if self.rect.left < 0:
            self.rect.left = 0
            self.pos.x = 0
        if self.rect.right > SCREEN_WIDTH:
            self.rect.right = SCREEN_WIDTH
            self.pos.x = SCREEN_WIDTH - self.rect.width

        # Invincibility
        if self.invincible_timer > 0:
            self.invincible_timer -= 1

        # Collect items
        for item in collectibles[:]:
            if self.rect.colliderect(item.rect):
                self.score += item.value
                for _ in range(8):
                    particles.append(Particle(item.rect.centerx, item.rect.centery, YELLOW, lifetime=20))
                collectibles.remove(item)

        # Enemy collision
        if self.invincible_timer == 0:
            for enemy in enemies:
                if self.rect.colliderect(enemy.rect):
                    if self.vel.y > 0 and self.rect.bottom < enemy.rect.centery + 10:
                        # Stomp enemy
                        enemy.die()
                        self.vel.y = self.JUMP_FORCE * 0.7
                        self.score += 100
                        for _ in range(10):
                            particles.append(Particle(enemy.rect.centerx, enemy.rect.centery, RED))
                    else:
                        self.take_damage(particles)

    def _handle_platform_collision_x(self, platforms):
        for p in platforms:
            if self.rect.colliderect(p.rect):
                if self.vel.x > 0:
                    self.rect.right = p.rect.left
                elif self.vel.x < 0:
                    self.rect.left = p.rect.right
                self.pos.x = float(self.rect.x)
                self.vel.x = 0

    def _handle_platform_collision_y(self, platforms):
        for p in platforms:
            if self.rect.colliderect(p.rect):
                if self.vel.y > 0:
                    self.rect.bottom = p.rect.top
                    self.on_ground = True
                elif self.vel.y < 0:
                    self.rect.top = p.rect.bottom
                self.pos.y = float(self.rect.y)
                self.vel.y = 0

    def take_damage(self, particles):
        self.health -= 1
        self.invincible_timer = 90
        for _ in range(15):
            particles.append(Particle(self.rect.centerx, self.rect.centery, RED))

    def draw(self, surface):
        if self.invincible_timer > 0 and self.invincible_timer % 6 < 3:
            return
        sprite = self.image
        if not self.facing_right:
            sprite = pygame.transform.flip(sprite, True, False)
        surface.blit(sprite, self.rect)

    def draw_hud(self, surface):
        # Health hearts
        for i in range(self.max_health):
            color = RED if i < self.health else GRAY
            pygame.draw.polygon(surface, color, [
                (20 + i*35, 25), (14 + i*35, 17), (8 + i*35, 22),
                (8 + i*35, 28), (20 + i*35, 38), (32 + i*35, 28),
                (32 + i*35, 22), (26 + i*35, 17)
            ])
        # Score
        font = pygame.font.Font(None, 36)
        score_text = font.render(f"Score: {self.score}", True, WHITE)
        surface.blit(score_text, (SCREEN_WIDTH - 180, 10))


class Platform(pygame.sprite.Sprite):
    def __init__(self, x, y, w, h, color=None):
        super().__init__()
        self.rect = pygame.Rect(x, y, w, h)
        self.color = color or (80, 60, 40)
        self.image = pygame.Surface((w, h))
        self._draw()

    def _draw(self):
        self.image.fill(self.color)
        # Top highlight
        pygame.draw.rect(self.image, tuple(min(255,c+40) for c in self.color), (0,0,self.rect.width,6))
        # Bottom shadow
        pygame.draw.rect(self.image, tuple(max(0,c-40) for c in self.color), (0,self.rect.height-4,self.rect.width,4))

    def draw(self, surface):
        surface.blit(self.image, self.rect)


class Enemy(pygame.sprite.Sprite):
    def __init__(self, x, y, patrol_range=100):
        super().__init__()
        self.rect = pygame.Rect(x, y, 36, 36)
        self.pos = Vector2(x, y)
        self.vel = Vector2(2, 0)
        self.start_x = x
        self.patrol_range = patrol_range
        self.alive = True

    def update(self):
        if not self.alive:
            return
        self.pos.x += self.vel.x
        self.rect.x = int(self.pos.x)
        if abs(self.pos.x - self.start_x) > self.patrol_range:
            self.vel.x *= -1

    def die(self):
        self.alive = False
        self.kill()

    def draw(self, surface):
        if not self.alive:
            return
        # Body
        pygame.draw.rect(surface, RED, self.rect, border_radius=6)
        # Eyes
        ex = self.rect.x
        ey = self.rect.y
        pygame.draw.circle(surface, WHITE, (ex+10, ey+12), 6)
        pygame.draw.circle(surface, WHITE, (ex+26, ey+12), 6)
        pygame.draw.circle(surface, BLACK, (ex+11, ey+12), 3)
        pygame.draw.circle(surface, BLACK, (ex+27, ey+12), 3)
        # Mouth
        pygame.draw.arc(surface, BLACK, (ex+8, ey+20, 20, 10), 3.14, 0, 2)


class Collectible(pygame.sprite.Sprite):
    def __init__(self, x, y, value=10, color=YELLOW):
        super().__init__()
        self.rect = pygame.Rect(x, y, 20, 20)
        self.value = value
        self.color = color
        self.float_offset = random.uniform(0, 6.28)
        self.float_timer = 0

    def update(self):
        self.float_timer += 0.05
        self.rect.y = int(self.rect.y + math.sin(self.float_timer + self.float_offset) * 0.3)

    def draw(self, surface):
        pygame.draw.circle(surface, self.color, self.rect.center, 10)
        pygame.draw.circle(surface, WHITE, (self.rect.centerx-3, self.rect.centery-3), 3)


