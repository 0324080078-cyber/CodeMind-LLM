@dataclass
class Vector2:
    x: float = 0.0
    y: float = 0.0

    def __add__(self, other):
        return Vector2(self.x + other.x, self.y + other.y)

    def length(self) -> float:
        return math.sqrt(self.x**2 + self.y**2)

    def normalize(self):
        l = self.length()
        if l > 0:
            return Vector2(self.x/l, self.y/l)
        return Vector2()


